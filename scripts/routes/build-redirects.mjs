#!/usr/bin/env node
// Emits public/_redirects from data/routes/redirects.json.
//
// The data file speaks the route manifest's vocabulary: slash-less paths. The
// URL form is applied here, at the point of emission, and two things had to
// change about it.
//
// 1. Destinations get the trailing slash. Cloudflare Pages serves this build's
//    directory output as `/foo/` and 308-redirects `/foo`, so a 301 to /pricing
//    made a crawler take two hops to reach /pricing/.
//
// 2. Every source is emitted in BOTH forms. Pages matches _redirects literally.
//    The URL Google has indexed for a retired page is the trailing-slash one -
//    it is what that page's own canonical tag and the sitemap named - and only
//    the slash-less form had a rule. Measured on the live origin before this
//    change: /blog/what-should-i-know-about-pricing returned 301, and
//    /blog/what-should-i-know-about-pricing/ returned 404. Forty-two retired
//    URLs were serving a 404 at exactly the address that was indexed.
//
// The five absolute-URL rules that used to head this file
// (https://www.approvalprep.com/* -> apex, and the same for the two parked
// domains) are gone. That is Netlify syntax; Pages matches by path and never
// looked at the Host header, so they had never fired: www.approvalprep.com
// served the whole site at 200 alongside the apex. Host canonicalisation now
// lives in functions/_middleware.js, which does see the Host header.
import fs from "node:fs";

const data = JSON.parse(fs.readFileSync("data/routes/redirects.json", "utf8"));

const servingForm = (rawPath) => {
  const last = String(rawPath).split("/").pop() || "";
  if (/\.[a-z0-9]+$/i.test(last)) return rawPath;
  return `${String(rawPath).replace(/\/+$/, "")}/`;
};

const header = [
  "# GENERATED by scripts/routes/build-redirects.mjs from data/routes/redirects.json.",
  "# Edit that file, then run `npm run routes:redirects`.",
  "#",
  "# Each source is emitted twice, slash-less and trailing-slash, because Pages",
  "# matches these rules literally and the indexed URL of a retired page is the",
  "# trailing-slash one. Destinations name the 200-serving form so a redirect is",
  "# one hop, not two.",
  "#",
  "# Host canonicalisation (www and the parked domains) lives in",
  "# functions/_middleware.js. Absolute-URL sources do not work here.",
  "",
];

const rows = [];
for (const r of (data.redirects || []).slice().sort((a, b) => a.source.localeCompare(b.source))) {
  const destination = servingForm(r.destination);
  const bare = String(r.source).replace(/\/+$/, "") || "/";
  rows.push(`${bare} ${destination} ${r.statusCode}`);
  if (bare !== "/") rows.push(`${bare}/ ${destination} ${r.statusCode}`);
}

fs.writeFileSync("public/_redirects", [...header, ...rows, ""].join("\n"));
console.log(`[redirects] OK sources=${(data.redirects || []).length} rulesEmitted=${rows.length}`);
